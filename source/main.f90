PROGRAM MAIN
  USE KEYS, ONLY: ACTION,NTRIALS,DOMLEN,NREG,REGPOS,NTYPE,NPART,NPROT,PRAD,VEL,&
                  DIFFCONST,KREV,STARTPOS,STARTSTATE,MAXNPART
  USE PARTICLEUTILS, ONLY: PARTICLE,PARTICLEGROUP,DOMAIN,&
                            MAKEPARTICLE,DELETEPARTICLE,SETUPPARTICLEGROUP,&
                            CLEANUPPARTICLEGROUP,SETUPDOMAIN,CLEANUPDOMAIN,&
                            OUTPUTSNAPSHOT

  IMPLICIT NONE
  DOUBLE PRECISION :: T1,T2
  TYPE(PARTICLE), POINTER :: PLIST(:)
  TYPE(PARTICLE), POINTER :: PARTP
  TYPE(PARTICLEGROUP), POINTER :: GROUPLIST(:)
  TYPE(PARTICLEGROUP), POINTER :: PGROUP
  TYPE(DOMAIN), TARGET :: DOM
  TYPE(DOMAIN), POINTER :: DOMP

  INTEGER :: TC,PC,CC,PID

  ! start timer
  CALL CPU_TIME(T1)
  ! print*, 'time: ', t1

  ! parses free format input file
  CALL READKEY
  PRINT*, SUM(NPART)

  ! initialize particle arrays
  ALLOCATE(GROUPLIST(NTRIALS))
  ALLOCATE(PLIST(MAXNPART))

  ! set up simulation domain
  DOMP=>DOM
  CALL SETUPDOMAIN(DOMP,DOMLEN,NREG,REGPOS)

  SELECT CASE(ACTION)
    CASE('DOFUSION')
      DO TC = 1,NTRIALS
        !PRINT*, 'TESTXB: TC,NTRIALS: ',TC,NTRIALS
        PGROUP=>GROUPLIST(TC)
        PID = 1
        DO PC = 1,NTYPE
          DO CC = 1,NPART(PC)
            ! PRINT*, 'TESTXA: PC, CC, NPART(PC)',PC, CC,NPART(PC)
            ! PRINT*, 'TESTXC, STARTPOS: ',STARTPOS(PC)
            PARTP=>PLIST(PID)
            CALL MAKEPARTICLE(PARTP,PID,PC,NTYPE,NPROT,PRAD(PC),VEL(PC),D(PC),&
            KREV(PC),STARTPOS(PC),STARTSTATE(PC))
            PID = PID+1
          END DO
        END DO
        CALL SETUPPARTICLEGROUP(PGROUP,SUM(NPART),NTYPE,NPROT,PLIST)
      END DO
      !insert code to run requested action
        !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
      CALL FUSIONDRIVER(GROUPLIST,DOMP)

    CASE DEFAULT
    PRINT*, 'ERROR IN MAIN: unidentified action', ACTION
    STOP 1
  END SELECT

  !clean up arrays and deallocate memory
  DO PC = 1,SUM(NPART)
    PARTP=>PLIST(PC)
    CALL DELETEPARTICLE(PARTP)
  END DO

  DO TC = 1,NTRIALS
    PGROUP=>GROUPLIST(TC)
    CALL CLEANUPPARTICLEGROUP(PGROUP)
  END DO
  DEALLOCATE(GROUPLIST)
  
  CALL CLEANUPDOMAIN(DOMP)
  
  CALL CPU_TIME(T2)
  PRINT*,''
  PRINT '(A8,F8.3,A1)','Runtime:', T2-T1,'s'

  CONTAINS  
    SUBROUTINE FUSIONDRIVER(GROUPLIST,DOM)
    ! run fusion dynamics
      USE PARTDYNAMICS, ONLY: TRANSPORTSIM
      IMPLICIT NONE
      TYPE(PARTICLEGROUP), TARGET :: GROUPLIST(NTRIALS)
      TYPE(DOMAIN), POINTER :: DOM
      TYPE(PARTICLEGROUP), POINTER :: PGROUP
      
      PGROUP=>GROUPLIST(1)
      ! PRINT*,'TEXTX, SIZE(PLIST): ',SIZE(PGROUP%PLIST)
      CALL TRANSPORTSIM(PGROUP,DOMP,.FALSE.)
    END SUBROUTINE FUSIONDRIVER

END PROGRAM MAIN