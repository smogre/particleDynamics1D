PROGRAM MAIN
  USE KEYS, ONLY: ACTION,NTRIALS,DOMLEN,NREG,REGPOS,NTYPE,NPART,MAXNPART
  USE PARTICLEUTILS, ONLY: PARTICLE,PARTICLEGROUP,DOMAIN,&
                            MAKEPARTICLE,DELETEPARTICLE,SETUPPARTICLEGROUP,&
                            CLEANUPPARTICLEGROUP,SETUPDOMAIN,CLEANUPDOMAIN,&
                            OUTPUTSNAPSHOT,PARTICLEPARAMS,SETUPPARTICLEPARAMS,&
                            CLEANUPPARTICLEPARAMS

  IMPLICIT NONE
  DOUBLE PRECISION :: T1,T2
  TYPE(PARTICLE), TARGET :: PARTLIST(MAXNPART)
  TYPE(PARTICLE), POINTER :: PLIST(:)
  TYPE(PARTICLE), POINTER :: PARTP
  TYPE(PARTICLEGROUP), POINTER :: GROUPLIST(:)
  TYPE(PARTICLEGROUP), POINTER :: PGROUP
  TYPE(PARTICLEPARAMS), TARGET :: PARTPARAMS
  TYPE(PARTICLEPARAMS), POINTER :: PARAMP
  TYPE(DOMAIN), TARGET :: DOM
  TYPE(DOMAIN), POINTER :: DOMP

  INTEGER :: TC,PC,CC,PID,NC,MC

  ! start timer
  CALL CPU_TIME(T1)
  ! print*, 'time: ', t1

  ! parse free format input file
  CALL READKEY
  PARAMP=>PARTPARAMS
  CALL SETUPPARTICLEPARAMS(PARAMP)
  
  ! initialize particle arrays
  ALLOCATE(GROUPLIST(NTRIALS))
  ALLOCATE(PLIST(PARAMP%MAXNPART))

  ! set up simulation domain
  DOMP=>DOM
  CALL SETUPDOMAIN(DOMP,DOMLEN,NREG,REGPOS)

  SELECT CASE(ACTION)
    CASE('DOFUSION')
      DO TC = 1,NTRIALS
        PGROUP=>GROUPLIST(TC)
        PID = 1
        DO PC = 1,NTYPE
          DO CC = 1,NPART(PC)
            PARTP=>PLIST(PID)
            CALL MAKEPARTICLE(PARTP,PID,PC,PARAMP)
            PID = PID+1
          END DO
        END DO
        CALL SETUPPARTICLEGROUP(PGROUP,NPART,PLIST)
      END DO
      !insert code to run requested action
        !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
      CALL FUSIONDRIVER(GROUPLIST,PARAMP,DOMP)

    CASE DEFAULT
    PRINT*, 'ERROR IN MAIN: unidentified action', ACTION
    STOP 1
  END SELECT

  !clean up arrays and deallocate memory
  ! DO PC = 1,MAXNPART
  !   PARTP=>PLIST(PC)
  !   IF(PARTP%ARRAYSET) THEN
  !     CALL DELETEPARTICLE(PARTP)
  !   END IF
  ! END DO

  DO TC = 1,NTRIALS
    PGROUP=>GROUPLIST(TC)
    CALL CLEANUPPARTICLEGROUP(PGROUP)
  END DO
  DEALLOCATE(GROUPLIST)
  
  CALL CLEANUPPARTICLEPARAMS(PARAMP)
  CALL CLEANUPDOMAIN(DOMP)
  
  CALL CPU_TIME(T2)
  PRINT*,''
  PRINT '(A8,F8.3,A1)','Runtime:', T2-T1,'s'

  CONTAINS  
    SUBROUTINE FUSIONDRIVER(GROUPLIST,PARAMP,DOMP)
    ! run fusion dynamics
      USE PARTDYNAMICS, ONLY: TRANSPORTSIM
      IMPLICIT NONE
      TYPE(PARTICLEGROUP), TARGET :: GROUPLIST(NTRIALS)
      TYPE(PARTICLEPARAMS), POINTER :: PARAMP
      TYPE(DOMAIN), POINTER :: DOMP
      TYPE(PARTICLEGROUP), POINTER :: PGROUP
      
      PGROUP=>GROUPLIST(1)
      ! PRINT*,'TEXTX, SIZE(PLIST): ',SIZE(PGROUP%PLIST)
      CALL TRANSPORTSIM(PGROUP,DOMP,PARAMP,DOFUSION=.FALSE.,APPENDTOFILE=.FALSE.)
    END SUBROUTINE FUSIONDRIVER

END PROGRAM MAIN