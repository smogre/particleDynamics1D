PROGRAM MAIN
  USE KEYS, ONLY: ACTION,APPENDSNAPSHOTS,NTRIALS,NPART,NMT
  USE PARTICLEUTIL, ONLY: PARTICLEGROUP,SETUPPARTICLEGROUP,INITIALIZESIMS,CLEANUPPARTICLEGROUP

  IMPLICIT NONE
  DOUBLE PRECISION :: T1,T2
  TYPE(PARTICLEGROUP), POINTER :: PARTGROUP(:)
  TYPE(PARTICLEGROUP), POINTER :: PARTP

  INTEGER :: TC

  ! start timer
  CALL CPU_TIME(T1)

  !parses free format input file
  CALL READKEY

  !initialize particle arrays
  ALLOCATE(PARTGROUP(NTRIALS))

  SELECT CASE(ACTION)
    CASE('TRANSPORTSIM')
      DO TC = 1,NTRIALS
        PARTP=>PARTGROUP(TC)
        CALL SETUPPARTICLEGROUP(PARTP,NPART,NMT)
        CALL INITIALIZESIMS(PARTP)
      END DO
      CALL TRANSPORTSIMDRIVER(PARTGROUP)
    CASE DEFAULT
    PRINT*, 'ERROR IN MAIN: unidentified action', ACTION
    STOP 1
  END SELECT

  !clean up arrays and deallocate memory
  DO TC = 1,NTRIALS
    PARTP=>PARTGROUP(TC)
    CALL CLEANUPPARTICLEGROUP(PARTP)
  END DO
  DEALLOCATE(PARTGROUP)

  CALL CPU_TIME(T2)
  PRINT*,''
  PRINT '(A8,F8.3,A1)','Runtime:', T2-T1,'s'

  CONTAINS  
    SUBROUTINE TRANSPORTSIMDRIVER(PARTGROUP)
      ! run transport sims on dynamic microtubules
      USE KEYS, ONLY: NTRIALS
      USE TRANSPORTUTIL, ONLY: TRANSPORTSIM

      IMPLICIT NONE
      TYPE(PARTICLEGROUP), TARGET :: PARTGROUP(NTRIALS)
      TYPE(PARTICLEGROUP), POINTER :: PARTP
      INTEGER :: TC
      
      PARTP=>PARTGROUP(1)

      DO TC = 1,NTRIALS
        PRINT*, 'ITERATION NUMBER: ',TC
        IF(TC.GT.1) APPENDSNAPSHOTS = .TRUE.
        PARTP=>PARTGROUP(TC)
        CALL TRANSPORTSIM(PARTP,APPENDSNAPSHOTS)
      END DO
    END SUBROUTINE TRANSPORTSIMDRIVER

END PROGRAM MAIN