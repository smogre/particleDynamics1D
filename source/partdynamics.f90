  !INSERT PARTICLE DYNAMICS CODE HERE
  SUBROUTINE TRANSPORTSIM(GROUPLIST,DOMP,PARAMP,NTRIALS,DOFUSION)
  !simulates the transport of phagosomes and lysosomes in a 1D domain
    USE PARTICLEUTILS, ONLY: PARTICLE,PARTICLEGROUP,PARTICLEPARAMS,DOMAIN,&
                            OUTPUTPROT,OUTPUTSNAPSHOT,REMOVEPARTICLE,OUTPUTNFUSEDIST
    USE KEYS, ONLY: MAXNPROT,PRINTEVERY,SNAPFILE,SNAPEVERY,OUTFILE,OUTEVERY,DELT,&
                    NSTEPS,FUSEDISTEVERY,NFUSEFILE
    USE FUSIONUTILS, ONLY: FUSEPARTICLES
    
    INTEGER, INTENT(IN) :: NTRIALS
    TYPE(PARTICLEGROUP), TARGET :: GROUPLIST(NTRIALS)
    TYPE(PARTICLEGROUP), POINTER :: PGROUP
    TYPE(PARTICLE), POINTER :: PLIST(:)
    TYPE(PARTICLE), POINTER :: PARTP
    TYPE(PARTICLEPARAMS), POINTER :: PARAMP
    TYPE(DOMAIN), POINTER :: DOMP
    
    LOGICAL, INTENT(IN) :: DOFUSION

    DOUBLE PRECISION, ALLOCATABLE :: INFO(:)
    INTEGER, ALLOCATABLE :: NFUSEDIST(:,:),FUSEDISTVAL(:,:),NPARTDIST(:,:),PARTDISTVAL(:,:)
    INTEGER :: TC,PC,TRC,NPROC,TOTNPART,SURVCT
    LOGICAL :: APPENDTOFILE
    DOUBLE PRECISION :: CELLPROT(MAXNPROT),AXPROT(MAXNPROT),TOTAXPROT(MAXNPROT)

    IF(PRINTEVERY.NE.0) THEN
      PRINT'(A5,I1,A4,I8)', 'Step ',0,' of ',NSTEPS
    END IF

    SURVCT = 0
    ! initial snapshot
    APPENDTOFILE = .FALSE.
    IF(SNAPEVERY.GT.0) THEN
      ALLOCATE(INFO(3))
      INFO = (/0D0,DFLOAT(NTRIALS),DOMP%DOMLEN/)
      CALL OUTPUTSNAPSHOT(GROUPLIST,SNAPFILE,INFO,NTRIALS,APPENDTOFILE)
    END IF

    ! initial protein content output
    IF(OUTEVERY.GT.0) THEN
      CELLPROT = 0D0
      AXPROT = 0D0
      TOTAXPROT = 0D0
      CALL OUTPUTPROT(0D0,CELLPROT,TOTAXPROT,OUTFILE,MAXNPROT,NTRIALS,APPENDTOFILE)
    END IF

    ! initial distribution of number of fusion events
    IF(FUSEDISTEVERY.GT.0) THEN
      ALLOCATE(NFUSEDIST(DOMP%NREG+1,PARAMP%NTYPE),FUSEDISTVAL(DOMP%NREG+1,PARAMP%NTYPE))
      ALLOCATE(NPARTDIST(DOMP%NREG+1,PARAMP%NTYPE),PARTDISTVAL(DOMP%NREG+1,PARAMP%NTYPE))
      NFUSEDIST = 0
      FUSEDISTVAL = 0
      NPARTDIST = 0
      PARTDISTVAL = 0
      CALL OUTPUTNFUSEDIST(0D0,NFUSEDIST,NPARTDIST,DOMP%NREG,PARAMP%NTYPE,NTRIALS,DOMP%REGPOS,&
                              DOMP%DOMLEN,NFUSEFILE,APPENDTOFILE)
    END IF

    ALLOCATE(PLIST(PARAMP%MAXNPART))
    APPENDTOFILE = .TRUE.
    DO TC = 1,NSTEPS
      
      ! print information on simulation status
      IF((PRINTEVERY.NE.0)) THEN
        IF(MOD(TC,PRINTEVERY).EQ.0) THEN
          PRINT'(A5,I8,A4,I8)', 'Step ',TC,' of ',NSTEPS
        END IF
      END IF
      
      TOTAXPROT = 0D0
      NFUSEDIST = 0
      NPARTDIST = 0
      ! go through all particle groups
      DO TRC = 1,NTRIALS
        PGROUP=>GROUPLIST(TRC)

        ! check for fusion
        IF(DOFUSION) THEN
          CALL FUSEPARTICLES(PGROUP,PARAMP)
        END IF

        ! move particles, change direction, and delete out of bounds
        PC = 1
        NPROC = 0
        TOTNPART = SUM(PGROUP%NPART)
        DO WHILE(NPROC.LT.TOTNPART.AND.SUM(PGROUP%NPART).GT.0)
          PARTP=>PGROUP%PLIST(PC)
          NPROC = NPROC + 1

          ! move particles
          PARTP%POS = PARTP%POS+PARTP%CURSTATE*PARTP%VEL*DELT

          ! delete particles that move out of bounds
          IF((PARTP%POS.GT.DOMP%DOMLEN).OR.(PARTP%POS.LT.0D0)) THEN
            IF(PARTP%POS.LT.0D0) THEN
              IF(PARTP%NPROT.GT.0.AND.OUTEVERY.GT.0) THEN
                CELLPROT(1:PARTP%NPROT) = CELLPROT(1:PARTP%NPROT)+PARTP%PROT
              END IF
            END IF
            IF(PARTP%POS.GT.DOMP%DOMLEN) THEN
              SURVCT = SURVCT+1
              ! PRINT*, SURVCT, 'PARTICLES REACHED DOMAIN END. ID: ',PARTP%ID
            END IF
            CALL REMOVEPARTICLE(PGROUP,PC)
            CYCLE
          END IF

          ! check if particle changes direction
          IF(GRND().LE.(1-EXP(-PARTP%KREV*DELT))) THEN
            PARTP%CURSTATE = -PARTP%CURSTATE
          END IF

          ! protein conversion
          ! ---------------------------------------
          ! change to matrix exponentiation
          ! ---------------------------------------
          IF(PARTP%NPROT.GT.0) THEN
            PARTP%PROT = PARTP%PROT+MATMUL(PARTP%PROTCONV,PARTP%PROT)*DELT
          END IF

          PC = PC+1
        END DO

        ! measure protein content in the axon
        IF(OUTEVERY.GT.0) THEN
          CALL GETAXPROT(AXPROT,PGROUP,MAXNPROT)
          TOTAXPROT(1:MAXNPROT) = TOTAXPROT(1:MAXNPROT)+AXPROT
        END IF

        ! record distribution of fusion events
        IF(FUSEDISTEVERY.GT.0) THEN
          IF(MOD(TC,FUSEDISTEVERY).EQ.0) THEN
            CALL GETNFUSEDIST(FUSEDISTVAL,PARTDISTVAL,PGROUP,DOMP%NREG,PARAMP%NTYPE,DOMP%REGPOS)
            NFUSEDIST = NFUSEDIST+FUSEDISTVAL
            NPARTDIST = NPARTDIST+PARTDISTVAL
            ! CALL OUTPUTNFUSEDIST(TC*DELT,FUSEDISTVAL,PARTDISTVAL,DOMP%NREG,PARAMP%NTYPE,NTRIALS,&
                                ! DOMP%REGPOS,DOMP%DOMLEN,NFUSEFILE,APPENDTOFILE)
          END IF
        END IF

        ! particle production
        CALL PRODUCEPARTICLES(PGROUP,PARAMP)      

      END DO

      ! output snapshot to file
      IF(SNAPEVERY.GT.0) THEN
        IF(MOD(TC,SNAPEVERY).EQ.0) THEN
          INFO(1) = TC*DELT
          CALL OUTPUTSNAPSHOT(GROUPLIST,SNAPFILE,INFO,NTRIALS,APPENDTOFILE)
        END IF
      END IF

      ! output protein flux to file
      IF(OUTEVERY.GT.0) THEN
        IF(MOD(TC,OUTEVERY).EQ.0) THEN
          CALL OUTPUTPROT(TC*DELT,CELLPROT,TOTAXPROT,OUTFILE,MAXNPROT,NTRIALS,APPENDTOFILE)
        END IF
      END IF

      ! output nfuse distribution to file
      IF(FUSEDISTEVERY.GT.0) THEN
        IF(MOD(TC,FUSEDISTEVERY).EQ.0) THEN
          CALL OUTPUTNFUSEDIST(TC*DELT,NFUSEDIST,NPARTDIST,DOMP%NREG,PARAMP%NTYPE,NTRIALS,&
                                DOMP%REGPOS,DOMP%DOMLEN,NFUSEFILE,APPENDTOFILE)
        END IF
      END IF

    END DO

    PRINT*, 'DYNAMICS DONE'

  END SUBROUTINE TRANSPORTSIM

  SUBROUTINE PRODUCEPARTICLES(PGROUP,PARAMP)
    USE PARTICLEUTILS, ONLY: PARTICLEGROUP,PARTICLEPARAMS,PARTICLE,MAKEPARTICLE
    USE KEYS, ONLY: DELT
    IMPLICIT NONE

    TYPE(PARTICLEGROUP), POINTER :: PGROUP
    TYPE(PARTICLEPARAMS), POINTER :: PARAMP

    TYPE(PARTICLE),POINTER :: PARTP

    INTEGER :: NC,PID

    DO NC = 1,PARAMP%NTYPE ! go through each type of particle
      ! check if particle is produced
      IF(GRND().LE.1-EXP(-PARAMP%KPROD(NC)*DELT)) THEN
        ! check if you have space for a new particle
        IF(SUM(PGROUP%NPART).GE.PGROUP%MAXNPART) THEN
          PRINT*, 'ERROR: too many particles added.',&
                   PGROUP%NPART, PGROUP%MAXNPART
          STOP 1
        END IF

        PARTP=>PGROUP%PLIST(SUM(PGROUP%NPART)+1)
        PID = PGROUP%LASTID+1
        CALL MAKEPARTICLE(PARTP,PID,NC,PARAMP,CANFUSE=.TRUE.)
        PGROUP%NPART(NC)  = PGROUP%NPART(NC) + 1
        PGROUP%LASTID = PID      
        ! PRINT*, 'TESTX: PARTICLE PRODUCED, PID, TYPE, POS:',PARTP%ID,PARTP%PTYPE,PARTP%POS
      END IF
    END DO

  END SUBROUTINE PRODUCEPARTICLES

  SUBROUTINE GETAXPROT(AXPROT,PGROUP,MAXNPROT)
  ! subroutine to measure amount of protein in the axon
    USE PARTICLEUTILS, ONLY: PARTICLEGROUP,PARTICLE
    IMPLICIT NONE
    DOUBLE PRECISION :: AXPROT(MAXNPROT)
    TYPE(PARTICLEGROUP), POINTER :: PGROUP
    TYPE(PARTICLE), POINTER :: PARTP
    INTEGER, INTENT(IN) :: MAXNPROT

    INTEGER :: PC

    AXPROT = 0D0
    DO PC = 1,SUM(PGROUP%NPART)
      PARTP=>PGROUP%PLIST(PC)
      IF(PARTP%NPROT.EQ.0) CYCLE
      AXPROT(1:PARTP%NPROT) = AXPROT(1:PARTP%NPROT) + PARTP%PROT
    END DO

  END SUBROUTINE GETAXPROT

  SUBROUTINE GETNFUSEDIST(FUSEDISTVAL,PARTDISTVAL,PGROUP,NREG,NTYPE,REGPOS)
  ! subroutine to obtain distribution of number of fusion events
    USE mt19937, ONLY: RNORM
    USE PARTICLEUTILS, ONLY: PARTICLEGROUP,PARTICLE
    IMPLICIT NONE
    TYPE(PARTICLEGROUP), POINTER :: PGROUP
    TYPE(PARTICLE), POINTER :: PARTP
    INTEGER :: FUSEDISTVAL(NREG+1,NTYPE),PARTDISTVAL(NREG+1,NTYPE),PC,NC
    INTEGER, INTENT(IN) :: NREG,NTYPE
    DOUBLE PRECISION, INTENT(IN) :: REGPOS(NREG)
    DOUBLE PRECISION :: BINEDGES(NREG+1)
    LOGICAL :: REGSET = .FALSE.

    FUSEDISTVAL = 0
    PARTDISTVAL = 0
    BINEDGES = (/0D0,REGPOS/)
    DO PC = 1,SUM(PGROUP%NPART)
      PARTP=>PGROUP%PLIST(PC)
      REGSET = .FALSE.
      ! NC = MAXLOC(BINEDGES,DIM=1,MASK=(PARTP%POS.GE.BINEDGES))
      NC = MIN(FLOOR(PARTP%POS*(NREG+1))+1,NREG+1)
      FUSEDISTVAL(NC,PARTP%PTYPE) = FUSEDISTVAL(NC,PARTP%PTYPE)+PARTP%NFUSE
      PARTDISTVAL(NC,PARTP%PTYPE) = PARTDISTVAL(NC,PARTP%PTYPE)+1
    END DO

  END SUBROUTINE GETNFUSEDIST
 
END MODULE PARTDYNAMICS
