MODULE FUSIONUTILS
! subroutines to simulate fusion events between particles
! VERSION BY: SAURABH MOGRE 
! DATE: MAY 2020

USE MT19937, ONLY: GRND,RNORM,GRND
USE PARTICLEUTILS, ONLY: PARTICLE,PARTICLEGROUP
  
IMPLICIT NONE

CONTAINS

  SUBROUTINE CHECKFUSION(CHECKFUSE,POS1,POS2,PTYPE1,PTYPE2,PRAD1,PRAD2)
  ! subroutine to check whether fusion occurs
    USE KEYS, ONLY: USEPFUSE,DELT,PFUSE,KFUSE
    DOUBLE PRECISION, INTENT(IN) :: POS1,POS2,PRAD1,PRAD2
    INTEGER, INTENT(IN) :: PTYPE1,PTYPE2
    DOUBLE PRECISION :: PF,SEP
    LOGICAL, INTENT(OUT) :: CHECKFUSE
    
    CHECKFUSE = .FALSE.
    SEP = ABS(POS1-POS2)
    ! check if particles touch
    IF(SEP.GT.(PRAD1+PRAD2)) THEN
      RETURN
    END IF

    IF(USEPFUSE) THEN
      PF = PFUSE(PTYPE1,PTYPE2)
    ELSE
      PF = 1-EXP(-KFUSE(PTYPE1,PTYPE2)*DELT)
    END IF

    IF(GRND().LE.PF) CHECKFUSE = .TRUE.

  END SUBROUTINE CHECKFUSION

  SUBROUTINE FUSEPART(PGROUP,PIND1,PIND2)
  ! subroutine to implement fusion
  ! deletes particle at pind2, and updates protein content for particle 1
    USE PARTICLEUTILS, ONLY: DELETEPARTICLE
    TYPE(PARTICLEGROUP), POINTER :: PGROUP
    TYPE(PARTICLE), POINTER :: PLIST(:)
    TYPE(PARTICLE), POINTER :: PART1,PART2
    INTEGER, INTENT(IN) :: PIND1,PIND2

    PLIST=>PGROUP%PLIST
    PART1 = PLIST(PIND1)
    PART2 = PLIST(PIND2)
    IF(PART1%PTYPE.NE.2) THEN
      PRINT*, 'ERROR IN FUSEPART, FIRST PARTICLE MUST BE AUTOPHAGOSOME'
      STOP 1
    END IF
    PART1%NFUSE = PART1%NFUSE+1
    CALL DELETEPARTICLE(PART2)

  END SUBROUTINE FUSEPART

END MODULE FUSIONUTILS